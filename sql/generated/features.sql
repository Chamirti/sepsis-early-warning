        CASE WHEN FiO2_hrs_since_raw > 24 THEN 24 ELSE FiO2_hrs_since_raw END AS FiO2_hrs_since,
        FiO2_n24,
        FiO2_last - FiO2_first24 AS FiO2_change24,
        pH_last,
        CASE WHEN pH_hrs_since_raw > 24 THEN 24 ELSE pH_hrs_since_raw END AS pH_hrs_since,
        pH_n24,
        pH_last - pH_first24 AS pH_change24,
        PaCO2_last,
        CASE WHEN PaCO2_hrs_since_raw > 24 THEN 24 ELSE PaCO2_hrs_since_raw END AS PaCO2_hrs_since,
        PaCO2_n24,
        PaCO2_last - PaCO2_first24 AS PaCO2_change24,
