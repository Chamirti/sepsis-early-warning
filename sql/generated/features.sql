        DBP_mean6,
        DBP_min6,
        DBP_max6,
        DBP_mean24,
        DBP_n6,
        DBP_last,
        CASE WHEN DBP_hrs_since_raw > 24 THEN 24 ELSE DBP_hrs_since_raw END AS DBP_hrs_since,
        DBP_mean6 - DBP_mean24 AS DBP_delta6_24,
        Resp_mean6,
        Resp_min6,
        Resp_max6,
        Resp_mean24,
        Resp_n6,
        Resp_last,
        CASE WHEN Resp_hrs_since_raw > 24 THEN 24 ELSE Resp_hrs_since_raw END AS Resp_hrs_since,
        Resp_mean6 - Resp_mean24 AS Resp_delta6_24,
        BaseExcess_last,
        CASE WHEN BaseExcess_hrs_since_raw > 24 THEN 24 ELSE BaseExcess_hrs_since_raw END AS BaseExcess_hrs_since,
        BaseExcess_n24,
