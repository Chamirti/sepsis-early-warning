        O2Sat_max6,
        O2Sat_mean24,
        O2Sat_n6,
        O2Sat_last,
        CASE WHEN O2Sat_hrs_since_raw > 24 THEN 24 ELSE O2Sat_hrs_since_raw END AS O2Sat_hrs_since,
        O2Sat_mean6 - O2Sat_mean24 AS O2Sat_delta6_24,
        Temp_mean6,
        Temp_min6,
        Temp_max6,
        Temp_mean24,
        Temp_n6,
        Temp_last,
        CASE WHEN Temp_hrs_since_raw > 24 THEN 24 ELSE Temp_hrs_since_raw END AS Temp_hrs_since,
        Temp_mean6 - Temp_mean24 AS Temp_delta6_24,
