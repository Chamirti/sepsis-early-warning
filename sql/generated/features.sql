        ICULOS - LAST_VALUE(CASE WHEN PTT IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS PTT_hrs_since_raw,
        FIRST_VALUE(PTT IGNORE NULLS) OVER w24 AS PTT_first24,
        COUNT(PTT) OVER w24 AS PTT_n24,
        LAST_VALUE(WBC IGNORE NULLS) OVER wall AS WBC_last,
        ICULOS - LAST_VALUE(CASE WHEN WBC IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS WBC_hrs_since_raw,
        FIRST_VALUE(WBC IGNORE NULLS) OVER w24 AS WBC_first24,
        COUNT(WBC) OVER w24 AS WBC_n24,
        LAST_VALUE(Platelets IGNORE NULLS) OVER wall AS Platelets_last,
        ICULOS - LAST_VALUE(CASE WHEN Platelets IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS Platelets_hrs_since_raw,
        FIRST_VALUE(Platelets IGNORE NULLS) OVER w24 AS Platelets_first24,
        COUNT(Platelets) OVER w24 AS Platelets_n24,
        SUM(CASE WHEN MAP < 65 THEN 1 ELSE 0 END) OVER w12 AS hrs_map_lt65_12,
        SUM(CASE WHEN HR > 90 THEN 1 ELSE 0 END) OVER w12 AS hrs_hr_gt90_12,
        SUM(CASE WHEN Resp > 20 THEN 1 ELSE 0 END) OVER w12 AS hrs_resp_gt20_12,
        COUNT(*) OVER w24 AS hours_available24
    FROM cohort_observations
    WINDOW
        w6   AS (PARTITION BY patient_id ORDER BY ICULOS RANGE BETWEEN 5 PRECEDING AND CURRENT ROW),
        w12  AS (PARTITION BY patient_id ORDER BY ICULOS RANGE BETWEEN 11 PRECEDING AND CURRENT ROW),
        w24  AS (PARTITION BY patient_id ORDER BY ICULOS RANGE BETWEEN 23 PRECEDING AND CURRENT ROW),
        wall AS (PARTITION BY patient_id ORDER BY ICULOS RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)
)
SELECT
    patient_id,
        ICULOS,
        hospital,
        split,
        SepsisLabel,
        Age,
        Gender,
        Unit1,
        Unit2,
        HospAdmTime,
        HR_mean6,
        HR_min6,
        HR_max6,
        HR_mean24,
        HR_n6,
        HR_last,
        CASE WHEN HR_hrs_since_raw > 24 THEN 24 ELSE HR_hrs_since_raw END AS HR_hrs_since,
        HR_mean6 - HR_mean24 AS HR_delta6_24,
        O2Sat_mean6,
