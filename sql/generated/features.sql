        COUNT(BaseExcess) OVER w24 AS BaseExcess_n24,
        LAST_VALUE(HCO3 IGNORE NULLS) OVER wall AS HCO3_last,
        ICULOS - LAST_VALUE(CASE WHEN HCO3 IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS HCO3_hrs_since_raw,
        FIRST_VALUE(HCO3 IGNORE NULLS) OVER w24 AS HCO3_first24,
        COUNT(HCO3) OVER w24 AS HCO3_n24,
        LAST_VALUE(FiO2 IGNORE NULLS) OVER wall AS FiO2_last,
        ICULOS - LAST_VALUE(CASE WHEN FiO2 IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS FiO2_hrs_since_raw,
        FIRST_VALUE(FiO2 IGNORE NULLS) OVER w24 AS FiO2_first24,
        COUNT(FiO2) OVER w24 AS FiO2_n24,
        LAST_VALUE(pH IGNORE NULLS) OVER wall AS pH_last,
        ICULOS - LAST_VALUE(CASE WHEN pH IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS pH_hrs_since_raw,
        FIRST_VALUE(pH IGNORE NULLS) OVER w24 AS pH_first24,
        COUNT(pH) OVER w24 AS pH_n24,
        LAST_VALUE(PaCO2 IGNORE NULLS) OVER wall AS PaCO2_last,
        ICULOS - LAST_VALUE(CASE WHEN PaCO2 IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS PaCO2_hrs_since_raw,
