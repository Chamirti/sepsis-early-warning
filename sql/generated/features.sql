        COUNT(PaCO2) OVER w24 AS PaCO2_n24,
        LAST_VALUE(SaO2 IGNORE NULLS) OVER wall AS SaO2_last,
        ICULOS - LAST_VALUE(CASE WHEN SaO2 IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS SaO2_hrs_since_raw,
        FIRST_VALUE(SaO2 IGNORE NULLS) OVER w24 AS SaO2_first24,
        COUNT(SaO2) OVER w24 AS SaO2_n24,
        LAST_VALUE(BUN IGNORE NULLS) OVER wall AS BUN_last,
        ICULOS - LAST_VALUE(CASE WHEN BUN IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS BUN_hrs_since_raw,
        FIRST_VALUE(BUN IGNORE NULLS) OVER w24 AS BUN_first24,
        COUNT(BUN) OVER w24 AS BUN_n24,
        LAST_VALUE(Calcium IGNORE NULLS) OVER wall AS Calcium_last,
        ICULOS - LAST_VALUE(CASE WHEN Calcium IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS Calcium_hrs_since_raw,
        FIRST_VALUE(Calcium IGNORE NULLS) OVER w24 AS Calcium_first24,
        COUNT(Calcium) OVER w24 AS Calcium_n24,
        LAST_VALUE(Chloride IGNORE NULLS) OVER wall AS Chloride_last,
        ICULOS - LAST_VALUE(CASE WHEN Chloride IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS Chloride_hrs_since_raw,
        FIRST_VALUE(Chloride IGNORE NULLS) OVER w24 AS Chloride_first24,
        COUNT(Chloride) OVER w24 AS Chloride_n24,
        LAST_VALUE(Creatinine IGNORE NULLS) OVER wall AS Creatinine_last,
        ICULOS - LAST_VALUE(CASE WHEN Creatinine IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS Creatinine_hrs_since_raw,
        FIRST_VALUE(Creatinine IGNORE NULLS) OVER w24 AS Creatinine_first24,
        COUNT(Creatinine) OVER w24 AS Creatinine_n24,
        LAST_VALUE(Glucose IGNORE NULLS) OVER wall AS Glucose_last,
        ICULOS - LAST_VALUE(CASE WHEN Glucose IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS Glucose_hrs_since_raw,
        FIRST_VALUE(Glucose IGNORE NULLS) OVER w24 AS Glucose_first24,
        COUNT(Glucose) OVER w24 AS Glucose_n24,
        LAST_VALUE(Lactate IGNORE NULLS) OVER wall AS Lactate_last,
        ICULOS - LAST_VALUE(CASE WHEN Lactate IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS Lactate_hrs_since_raw,
        FIRST_VALUE(Lactate IGNORE NULLS) OVER w24 AS Lactate_first24,
        COUNT(Lactate) OVER w24 AS Lactate_n24,
        LAST_VALUE(Magnesium IGNORE NULLS) OVER wall AS Magnesium_last,
        ICULOS - LAST_VALUE(CASE WHEN Magnesium IS NOT NULL THEN ICULOS END IGNORE NULLS) OVER wall AS Magnesium_hrs_since_raw,
        FIRST_VALUE(Magnesium IGNORE NULLS) OVER w24 AS Magnesium_first24,
